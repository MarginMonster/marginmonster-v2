/* The rule every lyric writer in the app is given.
 *
 * A tester typed "Bohemian Rhapsody" as the idea for a music video (2026-11-21) and the song that came
 * back opened with Queen's own first line, word for word — sung, put on screen as a caption, and one tap
 * from being posted. A theme that names a song is asking for a song LIKE it, and the writer was also told
 * to "tell EXACTLY this", so it obliged. One shared sentence, so the music video, the kids' sing-along and
 * the ad jingle can never drift apart on it. Pure. */
export const ORIGINAL_LYRICS_RULE =
  "ORIGINAL WORDS ONLY: every lyric line must be newly written for this piece. NEVER quote, continue, translate or closely rework the lyrics, hook or title of any existing song — even when the brief names one. A named song, artist or band is only a hint for the subject, mood and style: write new words, and give it a new title of its own.";
